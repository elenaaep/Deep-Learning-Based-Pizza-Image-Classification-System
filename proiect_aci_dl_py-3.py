# 4. ATTENTION MODULES
# ============================================================
class ECABlock(nn.Module):
    def __init__(self, channels, k_size=3):
        super().__init__()
        self.avg_pool = nn.AdaptiveAvgPool2d(1)
        self.conv = nn.Conv1d(1, 1, kernel_size=k_size, padding=(k_size - 1) // 2, bias=False)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        y = self.avg_pool(x)
        y = y.squeeze(-1).transpose(-1, -2)
        y = self.conv(y)
        y = self.sigmoid(y)
        y = y.transpose(-1, -2).unsqueeze(-1)
        return x * y

class CBAM(nn.Module):
    def __init__(self, channels):
        super().__init__()
        self.avg_pool = nn.AdaptiveAvgPool2d(1)
        self.max_pool = nn.AdaptiveMaxPool2d(1)
        self.mlp = nn.Sequential(
            nn.Conv2d(channels, channels // 16, 1, bias=False),
            nn.ReLU(inplace=True),
            nn.Conv2d(channels // 16, channels, 1, bias=False)
        )
        self.spatial_conv = nn.Conv2d(2, 1, kernel_size=7, padding=3, bias=False)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        ca = self.sigmoid(self.mlp(self.avg_pool(x)) + self.mlp(self.max_pool(x)))
        x = x * ca
        avg_s = torch.mean(x, dim=1, keepdim=True)
        max_s, _ = torch.max(x, dim=1, keepdim=True)
        sa = self.sigmoid(self.spatial_conv(torch.cat([avg_s, max_s], dim=1)))
        return x * sa

# ============================================================
# 5. DUAL BRANCH MODEL
# ============================================================
class DualBranchPizzaModel(nn.Module):
    def __init__(self):
        super().__init__()
        # Branch 1: B0
        self.b0 = models.efficientnet_b0(weights="IMAGENET1K_V1")
        for param in self.b0.parameters():
            param.requires_grad = False
        self.b0.classifier = nn.Identity()
        self.cbam = CBAM(1280)

        # Branch 2: B3
        self.b3 = models.efficientnet_b3(weights="IMAGENET1K_V1")
        for param in self.b3.parameters():
            param.requires_grad = False
        self.b3.classifier = nn.Identity()
        self.eca = ECABlock(1536)

        # Fusion Layer
        self.fc = nn.Sequential(
            nn.Linear(1280 + 1536, 512),
            nn.ReLU(inplace=True),
            nn.Dropout(0.5),
            nn.Linear(512, 1)
        )

    def forward(self, x):
        f0 = self.cbam(self.b0.features(x))
        f0 = torch.mean(f0, dim=(2, 3))

        f3 = self.eca(self.b3.features(x))
        f3 = torch.mean(f3, dim=(2, 3))

        combined = torch.cat([f0, f3], dim=1)
        return self.fc(combined)

