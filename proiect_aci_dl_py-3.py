print("=== INITIERE PROCES KNOWLEDGE DISTILLATION ===\n")

# ------------------------------------------------------------
# 1. CLASA CUSTOM DISTILLER (Compatibila Keras 3 / TensorFlow 2.16+)
# ------------------------------------------------------------
class Distiller(keras.Model):
    def __init__(self, student, teacher):
        super().__init__()
        self.teacher = teacher
        self.student = student

    def compile(self, optimizer, metrics, student_loss_fn, distillation_loss_fn, alpha=0.1, temperature=3.0):
        # Transmitem student_loss_fn ca loss principal in super() pentru a evita ValueError: No loss to compute
        super().compile(optimizer=optimizer, metrics=metrics, loss=student_loss_fn)
        self.student_loss_fn = student_loss_fn
        self.distillation_loss_fn = distillation_loss_fn
        self.alpha = alpha
        self.temperature = temperature

    def train_step(self, data):
        x, y = data
        # Reteaua Teacher ofera predictii "soft", fara a-si modifica greutatile
        teacher_predictions = self.teacher(x, training=False)

        with tf.GradientTape() as tape:
            # Reteaua Student se antreneaza activ
            student_predictions = self.student(x, training=True)

            # Pierderea clasica bazata pe etichetele reale (hard targets)
            student_loss = self.student_loss_fn(y, student_predictions)

            # Pierderea de distilare (KL Divergence pe distributiile Softmax "moi")
            distellation_loss = self.distillation_loss_fn(
                tf.nn.softmax(teacher_predictions / self.temperature, axis=1),
                tf.nn.softmax(student_predictions / self.temperature, axis=1),
            )

            # Combinarea liniara a celor doua functii de pierdere
            loss = self.alpha * student_loss + (1.0 - self.alpha) * distellation_loss

        # Calculam si aplicam gradientele exclusiv pentru Student
        trainable_vars = self.student.trainable_variables
        gradients = tape.gradient(loss, trainable_vars)
        self.optimizer.apply_gradients(zip(gradients, trainable_vars))

        self.compiled_metrics.update_state(y, student_predictions)

        results = {m.name: m.result() for m in self.metrics}
        results.update({"student_loss": student_loss, "distillation_loss": distellation_loss})
        return results

    def test_step(self, data):
        # Pasul de testare apelat automat de Keras la finalul fiecarei epoci pe validation_data
        x, y = data
        student_predictions = self.student(x, training=False)
        student_loss = self.student_loss_fn(y, student_predictions)

        self.compiled_metrics.update_state(y, student_predictions)

        results = {m.name: m.result() for m in self.metrics}
        results.update({"student_loss": student_loss})
        return results

    def call(self, x):
        return self.student(x)

