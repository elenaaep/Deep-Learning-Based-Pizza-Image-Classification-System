def grad_cam(model, img_tensor, target_layer):
    model.eval()
    activations, gradients = [], []

    def fwd(_, __, out): activations.append(out)
    def bwd(_, __, grad): gradients.append(grad[0])

    h1 = target_layer.register_forward_hook(fwd)
    h2 = target_layer.register_full_backward_hook(bwd)

    # Output binar
    out = model(img_tensor.unsqueeze(0).to(DEVICE))
    score = torch.sigmoid(out)
    model.zero_grad()
    score.backward()

    # REPARATIE: Adaugam .detach() pentru a putea converti in numpy
    act = activations[0][0].detach().cpu().numpy()
    grad = gradients[0][0].detach().cpu().numpy()

    weights = grad.mean(axis=(1, 2))
    cam = np.maximum(np.sum(weights[:, None, None] * act, axis=0), 0)

    # Redimensionare si normalizare
    cam = cv2.resize(cam, (IMG_SIZE, IMG_SIZE))
    cam = (cam - cam.min()) / (cam.max() + 1e-8)

    h1.remove()
    h2.remove()
    return cam

